#!/usr/bin/env Rscript
suppressPackageStartupMessages(library(data.table))
args <- commandArgs(trailingOnly = TRUE)
root <- if (length(args)) normalizePath(args[[1]], mustWork = TRUE) else normalizePath(".", mustWork = TRUE)
gwas <- file.path(root, "results", "validation", "GWAS")
manifest_path <- Sys.getenv("SLDSC_MANIFEST_FILE", file.path(gwas, "sLDSC", "ldscores", "sldsc_annotation_manifest.tsv"))
m <- fread(manifest_path)
t <- fread(file.path(gwas, "SCENT_style", "config", "traits.tsv"))
j <- merge(m[, .(annotation_id, panel)], unique(t[, .(panel, trait)]), by = "panel", allow.cartesian = TRUE)
job_path <- Sys.getenv("SLDSC_JOB_FILE", file.path(gwas, "sLDSC", "ldscores", "sldsc_jobs.tsv"))
fwrite(j[, .(annotation_id, panel, trait)], job_path, sep = "\t")
